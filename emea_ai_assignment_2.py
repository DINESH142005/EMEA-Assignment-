import warnings
warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from ucimlrepo import fetch_ucirepo
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, PolynomialFeatures
from sklearn.linear_model import LinearRegression, Ridge, Lasso
from sklearn.metrics import mean_squared_error, r2_score

RANDOM_STATE = 42
pd.set_option("display.max_columns", 50)
sns.set_theme()
print("Libraries imported successfully.")

dataset = fetch_ucirepo(id=165)

X = dataset.data.features.copy()
y_raw = dataset.data.targets.copy()

# Convert any non-numeric columns to numeric values when possible.
X = X.apply(pd.to_numeric, errors="coerce")
y = pd.to_numeric(y_raw.iloc[:, 0], errors="coerce")

# Keep only rows with a valid target; missing feature values are imputed in the pipeline.
valid_target = y.notna()
X = X.loc[valid_target].reset_index(drop=True)
y = y.loc[valid_target].astype(float).reset_index(drop=True)

print("Feature shape:", X.shape)
print("Target shape:", y.shape)
print("\nFeature columns:")
print(X.columns.tolist())
display(X.head())
display(y.head().to_frame(name="concrete_strength"))

print("Data types:")
display(X.dtypes.astype(str).to_frame("dtype"))

print("Missing values per feature:")
display(X.isna().sum().to_frame("missing_count"))

print("Feature summary:")
display(X.describe().T)

print("Target summary:")
display(y.describe().to_frame("concrete_strength"))

plt.figure(figsize=(7, 4))
sns.histplot(y, kde=True)
plt.title("Distribution of Concrete Compressive Strength")
plt.xlabel("Compressive strength")
plt.ylabel("Count")
plt.tight_layout()
plt.show()

plt.figure(figsize=(10, 7))
sns.heatmap(pd.concat([X, y.rename("concrete_strength")], axis=1).corr(),
            annot=True, fmt=".2f", cmap="coolwarm", center=0)
plt.title("Feature and Target Correlation")
plt.tight_layout()
plt.show()

"""## 4. Split into training and test sets

Use an 80/20 split with a fixed random seed so results are reproducible. The test set is used only for final evaluation. Regression does not require stratification in this example.
"""

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=RANDOM_STATE
)

print("Training rows:", len(X_train))
print("Test rows:", len(X_test))

# def metrices and base for lin reb model
def regression_metrics(y_true, y_pred):
    mse = mean_squared_error(y_true, y_pred)
    rmse = np.sqrt(mse)
    r2 = r2_score(y_true, y_pred)
    return {"MSE": mse, "RMSE": rmse, "R2": r2}

baseline = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler()),
    ("model", LinearRegression())
])

baseline.fit(X_train, y_train)
baseline_train_pred = baseline.predict(X_train)
baseline_test_pred = baseline.predict(X_test)

baseline_results = pd.DataFrame([
    {"Model": "Linear Regression", "Split": "Train", **regression_metrics(y_train, baseline_train_pred)},
    {"Model": "Linear Regression", "Split": "Test", **regression_metrics(y_test, baseline_test_pred)}
])
display(baseline_results.round(4))

#polynomial reg
degrees = [1, 2, 3, 4]
polynomial_models = {}
polynomial_rows = []

for degree in degrees:
    pipe = Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="median")),
        ("poly", PolynomialFeatures(degree=degree, include_bias=False)),
        ("scaler", StandardScaler()),
        ("model", LinearRegression())
    ])
    pipe.fit(X_train, y_train)
    train_pred = pipe.predict(X_train)
    test_pred = pipe.predict(X_test)
    polynomial_models[degree] = pipe

    polynomial_rows.append({
        "Degree": degree,
        "Train MSE": mean_squared_error(y_train, train_pred),
        "Train RMSE": np.sqrt(mean_squared_error(y_train, train_pred)),
        "Train R2": r2_score(y_train, train_pred),
        "Test MSE": mean_squared_error(y_test, test_pred),
        "Test RMSE": np.sqrt(mean_squared_error(y_test, test_pred)),
        "Test R2": r2_score(y_test, test_pred)
    })

poly_results = pd.DataFrame(polynomial_rows)
display(poly_results.round(4))

fig, axes = plt.subplots(1, 2, figsize=(13, 4.5))

axes[0].plot(poly_results["Degree"], poly_results["Train RMSE"], marker="o", label="Train RMSE")
axes[0].plot(poly_results["Degree"], poly_results["Test RMSE"], marker="o", label="Test RMSE")
axes[0].set_title("RMSE by Polynomial Degree")
axes[0].set_xlabel("Polynomial degree")
axes[0].set_ylabel("RMSE (lower is better)")
axes[0].set_xticks(degrees)
axes[0].legend()

axes[1].plot(poly_results["Degree"], poly_results["Train R2"], marker="o", label="Train R²")
axes[1].plot(poly_results["Degree"], poly_results["Test R2"], marker="o", label="Test R²")
axes[1].set_title("R² by Polynomial Degree")
axes[1].set_xlabel("Polynomial degree")
axes[1].set_ylabel("R² (higher is better)")
axes[1].set_xticks(degrees)
axes[1].legend()

plt.tight_layout()
plt.show()

alphas = [0.01, 0.1, 1.0, 10.0, 100.0]
regularization_rows = []
regularized_models = {}

for model_name, estimator in [
    ("Ridge", Ridge()),
    ("Lasso", Lasso(max_iter=20000))
]:
    for alpha in alphas:
        pipe = Pipeline(steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("poly", PolynomialFeatures(degree=2, include_bias=False)),
            ("scaler", StandardScaler()),
            ("model", estimator.set_params(alpha=alpha))
        ])
        pipe.fit(X_train, y_train)
        train_pred = pipe.predict(X_train)
        test_pred = pipe.predict(X_test)
        regularized_models[(model_name, alpha)] = pipe

        regularization_rows.append({
            "Model": model_name,
            "Alpha": alpha,
            "Train MSE": mean_squared_error(y_train, train_pred),
            "Train RMSE": np.sqrt(mean_squared_error(y_train, train_pred)),
            "Train R2": r2_score(y_train, train_pred),
            "Test MSE": mean_squared_error(y_test, test_pred),
            "Test RMSE": np.sqrt(mean_squared_error(y_test, test_pred)),
            "Test R2": r2_score(y_test, test_pred)
        })

regularization_results = pd.DataFrame(regularization_rows)
display(regularization_results.round(4))

fig, axes = plt.subplots(1, 2, figsize=(13, 4.5))

for name in ["Ridge", "Lasso"]:
    subset = regularization_results[regularization_results["Model"] == name]
    axes[0].plot(subset["Alpha"], subset["Test RMSE"], marker="o", label=name)
    axes[1].plot(subset["Alpha"], subset["Test R2"], marker="o", label=name)

for ax in axes:
    ax.set_xscale("log")
    ax.set_xlabel("Regularization alpha (log scale)")
    ax.legend()

axes[0].set_title("Regularization: Test RMSE")
axes[0].set_ylabel("RMSE (lower is better)")
axes[1].set_title("Regularization: Test R²")
axes[1].set_ylabel("R² (higher is better)")

plt.tight_layout()
plt.show()

degree_to_plot = 2
chosen_poly = polynomial_models[degree_to_plot]
chosen_pred = chosen_poly.predict(X_test)

plt.figure(figsize=(6, 6))
plt.scatter(y_test, chosen_pred, alpha=0.6)
min_val = min(float(y_test.min()), float(np.min(chosen_pred)))
max_val = max(float(y_test.max()), float(np.max(chosen_pred)))
plt.plot([min_val, max_val], [min_val, max_val], linestyle="--")
plt.title(f"Actual vs Predicted — Polynomial Degree {degree_to_plot}")
plt.xlabel("Actual strength")
plt.ylabel("Predicted strength")
plt.tight_layout()
plt.show()

# Identify the degree with the lowest test RMSE in this run.
best_degree_row = poly_results.loc[poly_results["Test RMSE"].idxmin()]
print("Polynomial model with lowest test RMSE in this run:")
display(best_degree_row.to_frame("value"))

# Identify the lowest-test-RMSE regularized model in this run.
best_regularized_row = regularization_results.loc[regularization_results["Test RMSE"].idxmin()]
print("Regularized model with lowest test RMSE in this run:")
display(best_regularized_row.to_frame("value"))

print("Train/test RMSE gaps by degree:")
display(poly_results[["Degree", "Train RMSE", "Test RMSE"]].assign(
    RMSE_gap=lambda d: d["Test RMSE"] - d["Train RMSE"]
).round(4))
