from pathlib import Path
import os
import cv2
import matplotlib.pyplot as plt
import pandas as pd
from IPython.display import display, Image as IPyImage

from ultralytics import YOLO

print("Ultralytics and OpenCV are ready.")

model = YOLO("yolov8n.pt")
print("Model loaded:", model.model.__class__.__name__)
print("Number of COCO classes:", len(model.names))
print("Example class names:", list(model.names.items())[:10])

sample_image_url = "https://ultralytics.com/images/bus.jpg"
sample_image_path = "yolov8_sample_bus.jpg"

# Download the sample image.
import urllib.request
urllib.request.urlretrieve(sample_image_url, sample_image_path)

results = model.predict(
    source=sample_image_path,
    conf=0.25,
    save=True,
    project="runs/assignment9",
    name="sample",
    exist_ok=True,
    verbose=False
)

result = results[0]
annotated_bgr = result.plot()
annotated_rgb = cv2.cvtColor(annotated_bgr, cv2.COLOR_BGR2RGB)

plt.figure(figsize=(12, 8))
plt.imshow(annotated_rgb)
plt.axis("off")
plt.title("YOLOv8 Detection — Sample Image")
plt.show()

print("Annotated output directory:", result.save_dir)

# Print actual detections from the sample image.
detections = []
if result.boxes is not None and len(result.boxes) > 0:
    xyxy = result.boxes.xyxy.cpu().numpy()
    confs = result.boxes.conf.cpu().numpy()
    classes = result.boxes.cls.cpu().numpy().astype(int)

    for box, confidence, class_id in zip(xyxy, confs, classes):
        detections.append({
            "class_id": int(class_id),
            "class_name": model.names[int(class_id)],
            "confidence": float(confidence),
            "x1": float(box[0]),
            "y1": float(box[1]),
            "x2": float(box[2]),
            "y2": float(box[3])
        })

detections_df = pd.DataFrame(detections)
if detections_df.empty:
    print("No objects were detected above the confidence threshold.")
else:
    display(detections_df.round(4))
    print("Total detections:", len(detections_df))

IMAGE_PATH = None

if IMAGE_PATH is not None:
    image_path = Path(IMAGE_PATH)
    if not image_path.exists():
        raise FileNotFoundError(f"Image not found: {image_path}")

    custom_results = model.predict(
        source=str(image_path),
        conf=0.25,
        save=True,
        project="runs/assignment9",
        name="custom_image",
        exist_ok=True,
        verbose=False
    )
    custom_result = custom_results[0]
    custom_rgb = cv2.cvtColor(custom_result.plot(), cv2.COLOR_BGR2RGB)

    plt.figure(figsize=(12, 8))
    plt.imshow(custom_rgb)
    plt.axis("off")
    plt.title("YOLOv8 — Your Image")
    plt.show()

    print("Saved output:", custom_result.save_dir)
else:
    print("Custom image detection skipped. Set IMAGE_PATH to run it.")

VIDEO_PATH = None

if VIDEO_PATH is not None:
    video_path = Path(VIDEO_PATH)
    if not video_path.exists():
        raise FileNotFoundError(f"Video not found: {video_path}")

    video_results = model.predict(
        source=str(video_path),
        conf=0.25,
        save=True,
        project="runs/assignment9",
        name="video",
        exist_ok=True,
        stream=True,
        verbose=False
    )
    frame_count = 0
    total_detections = 0
    for frame_result in video_results:
        frame_count += 1
        if frame_result.boxes is not None:
            total_detections += len(frame_result.boxes)

    print("Frames processed:", frame_count)
    print("Total detections across processed frames:", total_detections)
    print("Annotated video output folder: runs/assignment9/video")
else:
    print("Video detection skipped. Set VIDEO_PATH to run it.")

WEBCAM_SOURCE = None

if WEBCAM_SOURCE is not None:
    cap = cv2.VideoCapture(WEBCAM_SOURCE)
    if not cap.isOpened():
        cap.release()
        raise RuntimeError("Could not open webcam. Check camera permissions and source index.")

    print("Webcam started. Press 'q' in the video window to stop.")
    try:
        while True:
            ok, frame = cap.read()
            if not ok:
                print("Could not read a frame; stopping.")
                break

            frame_result = model.predict(frame, conf=0.25, verbose=False)[0]
            annotated = frame_result.plot()
            cv2.imshow("YOLOv8 Real-Time Detection", annotated)

            if cv2.waitKey(1) & 0xFF == ord("q"):
                break
    finally:
        cap.release()
        cv2.destroyAllWindows()
else:
    print("Webcam mode skipped. Set WEBCAM_SOURCE = 0 in local Jupyter to enable it.")

print("RESULTS SUMMARY — sample image")
print("=" * 45)
print("Model: YOLOv8n pretrained weights (yolov8n.pt)")
print("Confidence threshold: 0.25")
print("Input image:", sample_image_path)
print("Detections found:", len(detections_df))

if not detections_df.empty:
    print("\nDetected classes:")
    display(
        detections_df.groupby("class_name")
        .agg(
            detection_count=("class_name", "size"),
            mean_confidence=("confidence", "mean"),
            max_confidence=("confidence", "max")
        )
        .sort_values("detection_count", ascending=False)
        .round(4)
    )

